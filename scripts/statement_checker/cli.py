"""Command line: plain commands to list, show and record checks, for people, the
repository skill `check-statements`, CI and the paper."""
import argparse
import datetime
import os
import subprocess
import sys
from pathlib import Path

from . import checks, render
from .model import Model, TIERS

ROOT = Path(__file__).resolve().parents[2]


def git_user(root):
    try:
        out = subprocess.run(["git", "config", "user.name"], cwd=root, capture_output=True,
                             text=True, timeout=10).stdout.strip()
        return out or None
    except (OSError, subprocess.TimeoutExpired):
        return None


def counts(m):
    """Numbers for the report."""
    decl_kinds = {"definitions": 0, "theorems": 0}
    seen = set()
    for e in m.entries:
        for n, d in e.decls:
            if n in seen or d is None:
                continue
            seen.add(n)
            decl_kinds["definitions" if d.is_definition else "theorems"] += 1
    return decl_kinds, len(seen)


def report(m):
    """The Markdown summary of the checks."""
    today = datetime.date.today().isoformat()
    sts = {e.id: m.status(e) for e in m.entries}
    out = ["# Statement checks", "",
           f"Generated by `python3 scripts/check_statements.py --report` on {today}. An item is a "
           "blueprint node that names Lean declarations; it counts as checked by a reviewer "
           "when that reviewer's latest check of it is current (the Lean and source texts are "
           "unchanged since) and its verdict is `agrees` or `differs`. See "
           "`verification/README.md`.", ""]
    hdr = ("| Package | Items | Definitions | Checked by ≥ 1 | Checked by ≥ 2 | Stale | Differs "
           "| Unsure |")
    out += [hdr, "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    tot = [0] * 7
    for pk in m.packages():
        es = [e for e in m.entries if e.item.package == pk]
        row = [len(es), sum(1 for e in es if e.is_definition),
               sum(1 for e in es if sts[e.id].n >= 1), sum(1 for e in es if sts[e.id].n >= 2),
               sum(1 for e in es if sts[e.id].stale), sum(1 for e in es if sts[e.id].differs),
               sum(1 for e in es if sts[e.id].unsure)]
        tot = [a + b for a, b in zip(tot, row)]
        out.append(f"| `{pk}` | " + " | ".join(map(str, row)) + " |")
    out.append("| **Total** | " + " | ".join(f"**{x}**" for x in tot) + " |")
    out.append("")
    dist = {}
    for s in sts.values():
        dist[s.n] = dist.get(s.n, 0) + 1
    out += ["Items by number of reviewers who checked them:", "",
            "| Reviewers | Items |", "| ---: | ---: |"]
    for k in sorted(dist):
        out.append(f"| {k} | {dist[k]} |")
    out.append("")
    out += ["Items by priority:", "", "| Priority | Items | Checked by ≥ 1 | Checked by ≥ 2 |",
            "| --- | ---: | ---: | ---: |"]
    for t, name in TIERS.items():
        es = [e for e in m.entries if e.tier == t]
        out.append(f"| {name} | {len(es)} | {sum(1 for e in es if sts[e.id].n >= 1)} | "
                   f"{sum(1 for e in es if sts[e.id].n >= 2)} |")
    out.append("")
    kinds, ndecl = counts(m)
    out.append(f"The items name {ndecl} distinct Lean declarations ({kinds['definitions']} "
               f"definitions, structures and their members; {kinds['theorems']} theorems, lemmas "
               f"and instances). {sum(1 for e in m.entries if e.sources)} items have a "
               f"transcribed source statement in `verification/sources.toml`.")
    out.append("")
    reviewers = {}
    for c in m.store.checks:
        reviewers.setdefault(c.reviewer, set()).add(c.item)
    if reviewers:
        out += ["| Reviewer | Items with a current check |", "| --- | ---: |"]
        for r in sorted(reviewers):
            cur = sum(1 for e in m.entries if r in sts[e.id].checked_by)
            out.append(f"| {r} | {cur} |")
        out.append("")
    basis = {}
    for e in m.entries:
        latest = checks.latest_by_reviewer(m.store.for_item(e.id))
        for r in sts[e.id].checked_by:
            b = latest[r].basis or "not recorded"
            basis[b] = basis.get(b, 0) + 1
    if basis:
        out += ["Current checks by what the statement was compared with (`paper`: the paper "
                "itself; `transcription`: the original statement in the sources files; "
                "`blueprint`: only the blueprint paraphrase, which is not the source):", "",
                "| Basis | Checks |", "| --- | ---: |"]
        out += [f"| {b} | {n} |" for b, n in sorted(basis.items())]
        out.append("")
    for title, key in (("Recorded differences", "differs"), ("Open questions (unsure)", "unsure")):
        rows = []
        for e in m.entries:
            latest = checks.latest_by_reviewer(m.store.for_item(e.id))
            for r in getattr(sts[e.id], key):
                c = latest[r]
                rows.append(f"- `{e.id}` ({r}, {c.date[:10]}): {c.comment}")
        if rows:
            out += [f"## {title}", ""] + rows + [""]
    stale = [e for e in m.entries if sts[e.id].stale]
    if stale:
        out += ["## Stale checks", "", "The Lean or source text of these items changed after "
                "the check; they must be checked again.", ""]
        latest_all = {e.id: checks.latest_by_reviewer(m.store.for_item(e.id)) for e in stale}
        for e in stale:
            for r in sts[e.id].stale:
                c = latest_all[e.id][r]
                parts = " and ".join(checks.stale_parts(c, e.lean_hash, e.source_hash))
                out.append(f"- `{e.id}`: {r} ({c.date[:10]}, {parts} changed)")
        out.append("")
    extra = m.defined_used_not_items()
    out += ["## Definitions outside the blueprint", "",
            f"{len(extra)} library definitions are used by the statements of items but are not "
            "named by any blueprint item, so no check covers them directly. The detail view lists "
            "them under each item (`--show`).", ""]
    if extra:
        out += ["<details><summary>The definitions, with the first item using each</summary>", ""]
        for n in sorted(extra):
            d = m.index.get(n)
            out.append(f"- `{n}` ({d.path}:{d.line}), used by `{extra[n][0]}`"
                       + (f" and {len(extra[n]) - 1} more" if len(extra[n]) > 1 else ""))
        out += ["", "</details>", ""]
    return "\n".join(out)


def validate(m):
    """Problems of the checks, the sources file and the blueprint names (empty if none)."""
    problems = []
    for f, line, msg in m.store.problems:
        problems.append(f"{m.store.dir.name}/{f}:{line}: {msg}")
    ids = set(m.by_id)
    for c in m.store.checks:
        if c.item not in ids:
            problems.append(f"{m.store.dir.name}/{c.file}:{c.line}: unknown item `{c.item}`")
        elif checks.slug(c.reviewer) != Path(c.file).stem:
            problems.append(f"{m.store.dir.name}/{c.file}:{c.line}: reviewer `{c.reviewer}` "
                            f"belongs in {checks.slug(c.reviewer)}.jsonl")
    for p in m.source_problems:
        problems.append(p)
    for s in m.source_entries:
        for i in s["items"]:
            if i not in ids:
                problems.append(f"{m.sources_path.name}: unknown item `{i}`")
    for e in m.entries:
        for n in e.missing:
            problems.append(f"{e.item.path}:{e.item.line}: \\lean{{{n}}} ({e.id}) is not "
                            "declared in the Lean sources (nor in Mathlib)")
    for name, ds in m.index.duplicates.items():
        if name in m.by_decl and sum(1 for d in ds if not d.private) > 1:
            places = ", ".join(f"{d.path}:{d.line}" for d in ds)
            problems.append(f"`{name}` is declared more than once: {places}")
    return problems


def matching(m, flt="all", package=None, query="", skip=()):
    """The entries in priority order that pass the filter."""
    for e in m.priority:
        st = m.status(e)
        if e.id in skip:
            continue
        if package and e.item.package != package:
            continue
        if flt == "unchecked" and st.n:
            continue
        if flt == "stale" and not st.stale:
            continue
        if flt == "differs" and not st.differs:
            continue
        if flt == "unsure" and not st.unsure:
            continue
        if flt == "unchecked-by-me" and st.mine is not None and not st.mine_stale \
                and st.mine.verdict != "unsure":
            continue
        if query and not all(w in e.search_text() for w in query.lower().split()):
            continue
        yield e, st


def list_items(m, flt="all", package=None, query=""):
    rows = []
    for e, st in matching(m, flt, package, query):
        mark = "*" if e.tier == 0 else "+" if e.tier == 1 else " "
        rows.append(f"{mark} {st.n} {e.item.package:<10} {e.kind:<5} {e.id:<45} "
                    f"{render.tex(e.item.title)}")
    return rows


def main(argv=None):
    ap = argparse.ArgumentParser(
        prog="check_statements.py",
        description="Check the Lean statements of Leanamics against their sources: list the "
                    "items, show one (source next to the Lean statement), record a check.")
    ap.add_argument("--reviewer", help="your name (default: git config user.name)")
    ap.add_argument("--root", default=str(ROOT), help=argparse.SUPPRESS)
    ap.add_argument("--checks-dir", help="directory of the checks (default: verification/checks)")
    ap.add_argument("--sources", help="sources file (default: verification/sources.toml)")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--report", action="store_true", help="print a Markdown summary of the checks")
    g.add_argument("--validate", action="store_true",
                   help="check the checks file, the sources file and the \\lean{} names")
    g.add_argument("--list", action="store_true", help="list the items as plain text")
    g.add_argument("--show", metavar="ID", help="print the detail view of an item")
    g.add_argument("--next", action="store_true",
                   help="print the id of the first item, in priority order, that passes --filter "
                        "(default: unchecked), --package and --search")
    g.add_argument("--context", metavar="ID",
                   help="print an item as Markdown with the full definitions its statement uses")
    g.add_argument("--record", metavar="ID",
                   help="record a check of an item by the reviewer (needs --verdict)")
    g.add_argument("--lean-type", metavar="ID",
                   help="ask Lean (lake env lean, slow) for the types of an item's declarations")
    ap.add_argument("--filter",
                    choices=["all", "unchecked", "unchecked-by-me", "stale", "differs", "unsure"],
                    help="with --list (default: all) or --next (default: unchecked)")
    ap.add_argument("--package", help="with --list or --next: only this package")
    ap.add_argument("--search", default="",
                    help="with --list or --next: only items matching these words")
    ap.add_argument("--skip", nargs="*", default=[], metavar="ID",
                    help="with --next: ignore these items")
    ap.add_argument("--verdict", choices=["agrees", "differs", "unsure"], help="with --record")
    ap.add_argument("--basis", choices=list(checks.BASES),
                    help="with --record: what the statement was compared with: the paper itself, "
                         "the transcription in the sources files, or only the blueprint")
    ap.add_argument("--comment", default="",
                    help="with --record: required for differs (what differs) and unsure "
                         "(the question)")
    ap.add_argument("--width", type=int, default=100, help="with --show: line width")
    ap.add_argument("--raw", action="store_true", help="with --show: LaTeX source")
    a = ap.parse_args(argv)
    root = Path(a.root)
    reviewer = a.reviewer or os.environ.get("CHECK_STATEMENTS_REVIEWER") or git_user(root)
    checks_dir = Path(a.checks_dir).resolve() if a.checks_dir else None
    m = Model(root, checks_dir=checks_dir, sources_file=a.sources, reviewer=reviewer)
    if a.report:
        print(report(m))
        return 0
    if a.validate:
        probs = validate(m)
        kinds, ndecl = counts(m)
        for p in probs:
            print("error:", p)
        print(f"{len(m.entries)} items, {ndecl} Lean declarations named "
              f"({kinds['definitions']} definitions, {kinds['theorems']} theorems), "
              f"{sum(len(e.item.lean) for e in m.entries)} \\lean{{}} names, "
              f"{sum(len(e.missing) for e in m.entries)} not found, "
              f"{len(m.store.checks)} checks, {len(m.source_entries)} source entries: "
              + ("FAILED" if probs else "OK"))
        return 1 if probs else 0
    if a.list:
        for r in list_items(m, a.filter or "all", a.package, a.search):
            print(r)
        return 0
    if a.next:
        for e, _ in matching(m, a.filter or "unchecked", a.package, a.search, set(a.skip)):
            print(e.id)
            return 0
        print("no item passes the filter", file=sys.stderr)
        return 1
    for opt in (a.show, a.context, a.lean_type, a.record):
        if opt and opt not in m.by_id:
            print(f"unknown item `{opt}` (ids look like voter:thm:21; see --list)",
                  file=sys.stderr)
            return 2
    if a.show:
        for text, _ in render.detail(m, m.by_id[a.show], a.width, raw=a.raw):
            print(text)
        return 0
    if a.context:
        print(render.item_context(m, m.by_id[a.context]))
        return 0
    if a.record:
        if not a.verdict or not a.basis:
            print("--record needs --verdict (agrees, differs, unsure) and --basis (paper, "
                  "transcription, blueprint)", file=sys.stderr)
            return 2
        try:
            c = m.record(m.by_id[a.record], a.verdict, a.comment, a.basis)
        except ValueError as err:
            print(f"nothing recorded: {err}", file=sys.stderr)
            return 2
        print(f"recorded: {c.item} {c.verdict} (basis: {c.basis}) by {c.reviewer} ({c.date}) in "
              f"verification/checks/{checks.slug(c.reviewer)}.jsonl")
        return 0
    if a.lean_type:
        from . import lean_check
        e = m.by_id[a.lean_type]
        print(lean_check.check_types(m, [n for n, d in e.decls if d is not None]))
        return 0
    ap.print_help()
    return 0
